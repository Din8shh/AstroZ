// Generates src/app/styles/tokens.css from the design system's tokens.json.
// Run: node scripts/build-tokens.mjs  (re-run whenever design/handoff is re-exported)
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'design/handoff/ds/astroz/tokens.json';
const OUT = 'src/app/styles/tokens.css';
const t = JSON.parse(readFileSync(SRC, 'utf8'));

// "{az-kumkum-ink}" aliases become var() references (the handoff CSS left them unresolved).
const val = (v) => String(v).replace(/^\{([a-z0-9-]+)\}$/, 'var(--$1)');
const decl = (name, v) => `  --${name}: ${val(v)};`;

const light = [], dark = [], shared = [];
for (const c of t.color.tokens) {
  light.push(decl(c.name, c.value.light));
  dark.push(decl(c.name, c.value.dark));
}
for (const s of t.shadow.tokens) {
  light.push(decl(s.name, s.value.light));
  dark.push(decl(s.name, s.value.dark));
}
for (const group of ['spacing', 'radius', 'size', 'scale']) {
  for (const s of t[group].tokens) shared.push(decl(s.name, s.value));
}
for (const [k, v] of Object.entries(t.type.families)) shared.push(`  --font-${k}: ${v};`);
for (const g of t.type.groups) {
  for (const s of g.styles) {
    const fam = s.family ?? g.family;
    shared.push(`  --text-${s.name}: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${fam});`);
  }
}

const fontFaces = t.type.fonts.map((f) =>
  `@font-face {\n  font-family: "${f.family}";\n  src: url("./${f.file}") format("woff2");\n` +
  `  font-weight: ${f.weight};\n  font-style: ${f.style};\n  font-display: swap;\n  unicode-range: ${f.unicodeRange};\n}`,
).join('\n');

const css = `/* GENERATED by scripts/build-tokens.mjs from ${SRC} (v${t.version}). Do not edit by hand. */
${fontFaces}

:root {
${shared.join('\n')}
${light.join('\n')}
  color-scheme: light;
}

/* Settings.theme = 'system' follows the OS; 'light' / 'dark' set data-theme on <html>. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${dark.map((l) => '  ' + l).join('\n')}
    color-scheme: dark;
  }
}
:root[data-theme='dark'] {
${dark.join('\n')}
  color-scheme: dark;
}
`;
writeFileSync(OUT, css);
console.log(`wrote ${OUT}: ${t.color.tokens.length} colours × 2 themes, ${t.type.fonts.length} font files`);
